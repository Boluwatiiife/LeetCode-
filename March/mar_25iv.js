// 6. 3Sum Closest

const threeSumClosest = function (nums, target) {
  nums.sort((a, b) => a - b);
  let closest_sum = Infinity;
  let n = nums.length;
  for (let i = 0; i < n - 2; i++) {
    let left = i + 1,
      right = n - 1;

    while (left < right) {
      let sum = nums[i] + nums[left] + nums[right];

      if (Math.abs(target - sum) < Math.abs(target - closest_sum)) {
        closest_sum = sum;
      }

      if (sum < target) {
        left++;
      } else if (sum > target) {
        right--;
      } else {
        return sum;
      }
    }
  }
  return closest_sum;
};

