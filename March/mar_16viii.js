// 2946. Matrix Similarity After Cyclic Shifts

const areSimilar = function (mat, k) {
  for (let i = 0; i < mat.length; i++) {
    let stri = "";

    for (no of mat[i]) stri += no.toString() + ",";
    let n = mat[0].length;
    let xx = Math.ceil(50 / n);
    let strr = "";

    for (let d = 0; d < xx + xx; d++) {
      strr += stri;
    }
    strr = strr.split(",");
    strr.pop();

    let arr = [];
    for (let x = k; x < k + n; x++) {
      arr.push(strr[x]);
    }

    stri = stri.split(",");
    stri.pop();
    stri = stri.join("");
    arr = arr.join("");

    if (stri !== arr) return false;
  }
  return true;
};

