// 1508. Range Sum of Sorted Subarray Sums

const rangeSum = function (nums, n, left, right) {
  const mod = 1e9 + 7;
  let arr = [];

  for (let i = 0; i < n; i++) {
    for (let j = i; j < n; j++) {
      arr.push(nums.slice(i, j + 1).reduce((a, b) => a + b, 0));
    }
  }
  arr.sort((a, b) => a - b);
  return arr.slice(left - 1, right).reduce((a, b) => a + b, 0) % mod;
};

