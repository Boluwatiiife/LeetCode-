// 823. Binary Trees With Factors

const numFactoredBinaryTrees = function (arr) {
  const MOD = 1e9 + 7;
  arr = arr.sort((a, b) => a - b);
  const n = arr.length;

  const mapp = new Map();
  for (let i = 0; i < n; i++) mapp.set(arr[i], i);

  let grid = Array(n).fill(1);

  for (let i = 0; i < n; i++) {
    for (let j = 0; j < i; j++) {
      if (arr[i] % arr[j] === 0) {
        const right = arr[i] / arr[j];
        if (mapp.has(right)) {
          const k = mapp.get(right);
          grid[i] = (grid[i] + ((grid[j] * grid[k]) % MOD)) % MOD;
        }
      }
    }
  }

  return grid.reduce((a, b) => (a + b) % MOD, 0);
};

