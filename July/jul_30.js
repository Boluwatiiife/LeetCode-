// 2419. Longest Subarray With Maximum Bitwise AND

const longestSubarray = function (nums) {
  const dex = nums.indexOf(Math.max(...nums));
  let maxx = nums[dex];
  let ans = 0;
  let count = 0;

  for (let i = dex; i < nums.length; i++) {
    if (nums[i] >= maxx) count++;
    else {
      ans = Math.max(ans, count);
      count = 0;
    }
  }
  ans = Math.max(ans, count);

  return ans;
};

